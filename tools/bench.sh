# bench.sh — the one canonical SonicBoom benchmark.
#
# Runs the canonical metric set for a GGUF and prints one table per model
# (SonicBoom, and llama.cpp + ratio unless --no-llama). Every metric is the
# median of `--runs` (default 3) independent process runs; each underlying tool
# ends its output with a single machine-readable `RESULT ...` line, which is what
# this script parses (never a free-text grep).
#
# Canonical set (CUDA spine, whole model resident on the GPU — llama.cpp -ngl 99):
#   tg64    decode 64 tokens from position 0        (llama-bench -p 0 -n 64 -d 0)
#   d512    decode 64 tokens at KV depth 512        (llama-bench -p 0 -n 64 -d 512)
#   d512-spec  the same, speculation left to the startup probe (no llama-bench
#           equivalent: it has no speculative decode)
#   pp512   whole-call prefill of 512 tokens from position 0
#                                               (llama-bench -p 512 -n 0 avg_ts)
#   reuse   512-token prefix + 64-token continuation, first-token latency
#           (SonicBoom's prefix cache; llama-bench has no equivalent)
#
# The decode tools warm the exact (model, n_ctx) runtime before the timed region,
# so the one-time graph/plan build + CUDA-graph capture is never counted. That is
# why tg64 reads the steady-state rate through this harness and not the lower
# number a warm-up keyed on a different n_ctx used to report (the capture cost
# leaked into the depth-0 tail). pp512 reports pp_whole (the whole N-token
# prefill from position 0, N / t_N, the same definition as llama-bench
# `-p n -n 0` avg_ts); pp_marginal stays in the tool's RESULT line as a
# diagnostic and pp_wall is a labelled legacy metric.
#
# Measurement conditions: the GPU clock is pinned for the duration of the run
# (`nvidia-smi -lgc`, released on exit with `-rgc`) — an unpinned clock drifts by
# more than the effects being compared. `--gpu-clock MHZ` picks the value (the
# device's max graphics clock by default) and `--no-lock-clocks` skips it. Pinning
# needs root, so when it is not possible the run is *not* clock-homogeneous and
# the number this script can give instead is the clock it actually ran at: the SM
# clock is sampled only while an item is being measured (plain `nvidia-smi`, no
# root), reported per item as min/median/max plus the sample count, and summed
# over all measurement windows at exit. Idle time between items is not in the
# record. The CPU governor is only *reported*; this script never changes a CPU
# setting.
#
# Every metric is the median of independent process runs, and the spread is
# reported beside it: the median alone cannot say whether a later comparison's
# difference is bigger than this harness's own repeatability.
#
# --long adds the extended-context tiers (M3): decode at depth 4K/8K/16K/32K and
# prefill of 4K/8K/16K/32K tokens, each against llama-bench at the same depth
# (`-d` / `-p`). It is opt-in because the deep tiers cost minutes per run. The
# decode tiers reach the depth with the chunked prefill path (longctx_bench
# --prefill) rather than decoding to it; the subtraction cancels the prefill,
# so the number is the steady decode rate with a depth-deep KV cache, the same
# thing llama-bench `-d` measures. Tiers whose n_ctx exceeds a model's declared
# context are reported as rejected by the runtime rather than as a number.
#
# --spec runs the code-edit comparison: ten frozen edit requests
# (tools/bench/codeedit; each turn is its own request), greedy,
# SonicBoom off/auto through codeedit_bench and, unless --no-llama,
# llama-server no-spec/ngram-mod through tools/bench/llama-codeedit.scm. Identity
# is per turn: a SonicBoom auto rep matches the off arm's token hash, a
# llama.cpp ngram-mod rep matches the no-spec arm's generated bytes.
# Speculation is off for the standard tiers and for every --long tier: they
# measure the runtime's own decode and prefill rates. --spec measures
# speculation explicitly, off and auto, and sets the value per process.
#
# --tune-export FILE writes the warm-up table the run resolved; --tune-import
# FILE starts from a table instead of measuring one. Either flag runs the
# SonicBoom arms from a fresh temporary tune directory, so the table holds the
# model under test only.
#
# Usage: tools/bench.sh <model.gguf> [--label NAME] [--runs N] [--no-build]
#                                       [--gpu-clock MHZ] [--no-lock-clocks]
#                                       [--long] [--spec] [--no-llama]
#                                       [--tune-export FILE] [--tune-import FILE]
# Env:   LLAMA_BIN=/path/to/llama.cpp/build/bin
#            the llama.cpp build (bin) directory, or any path inside it (a file
#            resolves to its directory). LLAMA_BENCH and LLAMA_SERVER are taken
#            from it unless set explicitly.
#        LLAMA_BENCH=/path/to/llama-bench    explicit llama-bench
#        LLAMA_SERVER=/path/to/llama-server  explicit llama-server (the
#            code-edit arms); when unset it is looked up next to LLAMA_BIN or
#            LLAMA_BENCH.
#        Without --no-llama both programs must be present: a missing one stops
#        the run before any measurement, because a comparison table without its
#        reference is not a result. --no-llama skips every llama.cpp arm.
set -euo pipefail

# Captured before this script exports anything of its own: the reproduction
# header reports the command and the environment the run was started with.
ORIG_ARGS=("$@")
SONICBOOM_ENV_AT_START=$(env | grep '^SONICBOOM_' | sort || true)

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BASELINE="$ROOT/tools/baseline"
RUNS=3
BUILD=1
LABEL=""
GGUF=""
CLOCKS=1
CLOCK_MHZ=""
LONG=0
LONG_DEPTHS="4096 8192 16384 32768"
LONG_STEPS=64
SPEC=0
NO_LLAMA=0
TUNE_EXPORT=""
TUNE_IMPORT=""

while [ $# -gt 0 ]; do
  case "$1" in
    --label) LABEL="$2"; shift 2 ;;
    --runs)  RUNS="$2";  shift 2 ;;
    --no-build) BUILD=0; shift ;;
    --gpu-clock) CLOCK_MHZ="$2"; shift 2 ;;
    --no-lock-clocks) CLOCKS=0; shift ;;
    --long) LONG=1; shift ;;
    --spec) SPEC=1; shift ;;
    --no-llama) NO_LLAMA=1; shift ;;
    --tune-export) TUNE_EXPORT="$2"; shift 2 ;;
    --tune-import) TUNE_IMPORT="$2"; shift 2 ;;
    -h|--help) awk '/^# SPDX/{f=1;next} /^set -euo pipefail/{f=0} f' "$0"; exit 0 ;;
    -*) echo "unknown option: $1" >&2; exit 2 ;;
    *)  GGUF="$1"; shift ;;
  esac
done

# LLAMA_BIN names a llama.cpp build directory; a path to a file inside it
# resolves to that file's directory. It fills the two binary paths that are not
# set explicitly; an explicit LLAMA_BENCH/LLAMA_SERVER keeps precedence. When
# only LLAMA_BENCH is given, llama-server is looked up beside it. A path that
# exists as neither a directory nor a file is taken as the directory it looks
# like, so the error below names the programs where the run expected them.
LLAMA_DIR=""
if [ -n "${LLAMA_BIN:-}" ]; then
  if [ -f "${LLAMA_BIN}" ]; then
    LLAMA_DIR="$(dirname "$LLAMA_BIN")"
  else
    LLAMA_DIR="$LLAMA_BIN"
  fi
fi
if [ -z "${LLAMA_BENCH:-}" ] && [ -n "$LLAMA_DIR" ]; then
  LLAMA_BENCH="$LLAMA_DIR/llama-bench"
fi
if [ -z "${LLAMA_SERVER:-}" ]; then
  if [ -n "$LLAMA_DIR" ]; then
    LLAMA_SERVER="$LLAMA_DIR/llama-server"
  elif [ -n "${LLAMA_BENCH:-}" ]; then
    LLAMA_SERVER="$(dirname "$LLAMA_BENCH")/llama-server"
  fi
fi
LLAMA_BENCH="${LLAMA_BENCH:-}"
LLAMA_SERVER="${LLAMA_SERVER:-}"

# The run count drives the reported spread, so a non-numeric one is an error,
# not a default.
case "$RUNS" in
  ''|*[!0-9]*) echo "runs must be a positive integer (got '$RUNS')" >&2; exit 2 ;;
esac
[ "$RUNS" -ge 1 ] || { echo "runs must be >= 1" >&2; exit 2; }

if [ -z "$GGUF" ]; then
  echo "usage: tools/bench.sh <model.gguf> [--label NAME] [--runs N] [--no-build]" >&2
  echo "                       [--long] [--spec] [--no-llama]" >&2
  echo "                       [--tune-export FILE] [--tune-import FILE]" >&2
  exit 2
fi
GGUF="$(readlink -f "$GGUF")"
[ -f "$GGUF" ] || { echo "model not found: $GGUF" >&2; exit 2; }
[ -n "$LABEL" ] || LABEL="$(basename "$GGUF" .gguf)"

# --- llama.cpp references ---------------------------------------------------
# A comparison table without its reference is not a result. Without --no-llama
# both programs must be present, and the check happens before anything is
# measured: a missing binary must not surface half a table later.
LLAMA_WARN=""
if [ "$NO_LLAMA" = 0 ]; then
  llama_missing=""
  { [ -n "$LLAMA_BENCH" ] && [ -x "$LLAMA_BENCH" ]; } || llama_missing="$llama_missing llama-bench"
  { [ -n "$LLAMA_SERVER" ] && [ -x "$LLAMA_SERVER" ]; } || llama_missing="$llama_missing llama-server"
  if [ -n "$llama_missing" ]; then
    {
      echo "error: llama.cpp program(s) not found:$llama_missing"
      echo "  llama-bench:  ${LLAMA_BENCH:-(unresolved: neither LLAMA_BIN nor LLAMA_BENCH is set)}"
      echo "  llama-server: ${LLAMA_SERVER:-(unresolved: no LLAMA_BIN, LLAMA_BENCH or LLAMA_SERVER is set)}"
      echo "  set LLAMA_BIN=/path/to/llama.cpp/build/bin (or name the programs"
      echo "  directly with LLAMA_BENCH=/path/to/llama-bench and"
      echo "  LLAMA_SERVER=/path/to/llama-server), or pass --no-llama to skip"
      echo "  every llama.cpp arm."
    } >&2
    exit 2
  fi
fi

# --- reproduction header ----------------------------------------------------
# Everything needed to repeat the run, printed before its first measurement.
echo "==== reproduction ===="
echo "command: $(printf '%q ' "$0" "${ORIG_ARGS[@]}")"
echo "LLAMA_BIN:    ${LLAMA_BIN:-(unset)}"
echo "LLAMA_SERVER: ${LLAMA_SERVER:-(unset)}"
if [ -n "$SONICBOOM_ENV_AT_START" ]; then
  echo "SONICBOOM_* env:"
  printf '%s\n' "$SONICBOOM_ENV_AT_START" | sed 's/^/  /'
else
  echo "SONICBOOM_* env: (none set)"
fi

# --- llama.cpp version ------------------------------------------------------
# Ratios are only comparable with a run against the same llama.cpp. Print the
# binaries' own version lines, and say so when the commit is not the pinned one.
echo
echo "[llama.cpp]"
if [ "$NO_LLAMA" = 1 ]; then
  echo "llama.cpp: skipped (--no-llama)"
else
  echo "llama-bench:  $LLAMA_BENCH"
  echo "llama-server: $LLAMA_SERVER"
  # llama.cpp prints --version on stderr (stdout carries the CUDA init lines), so
  # both streams are read; the version line is found by its own prefix.
  ll_bench_version=$("$LLAMA_BENCH" --version 2>&1 | sed -n 's/^version: *//p' | sed -n '1p' || true)
  ll_server_version=$("$LLAMA_SERVER" --version 2>&1 | sed -n 's/^version: *//p' | sed -n '1p' || true)
  ll_commit=$(printf '%s\n' "$ll_bench_version" |
    sed -n 's/.*commit \([0-9a-fA-F][0-9a-fA-F]*\).*/\1/p' | sed -n '1p')
  [ -n "$ll_commit" ] || ll_commit=$(printf '%s\n' "$ll_server_version" |
    sed -n 's/.*commit \([0-9a-fA-F][0-9a-fA-F]*\).*/\1/p' | sed -n '1p')
  echo "llama-bench version:  ${ll_bench_version:-unknown}"
  echo "llama-server version: ${ll_server_version:-unknown}"
  if [ -z "$ll_commit" ]; then
    echo "llama.cpp commit: unknown"
  else
    echo "llama.cpp commit: $ll_commit"
  fi
  case "$ll_commit" in
    43fe9*) ;;
    *)
      LLAMA_WARN="WARNING: llama.cpp is not 43fe9; ratios are not comparable with the README, which is measured against llama.cpp 43fe9."
      echo "$LLAMA_WARN" ;;
  esac

  # --- routed-expert offload ------------------------------------------------
  # A routed-expert model (GGUF expert_count > 0) does not fit an 8 GB card
  # with every weight in VRAM, so the llama.cpp arms keep the experts of the
  # first L layers on the host. L is the smallest count llama-bench allocates
  # with: every layer closer to the GPU stays there, and none is given up for
  # headroom the card does not need. Dense models get no extra argument.
  #
  # expert_count is read from the GGUF key-value block, whose layout is fixed
  # (uint64 key length, key bytes, uint32 value type, value); no SonicBoom
  # program reports it.
  gguf_u32() { # FILE KEY-SUFFIX -> UINT32 value, empty when absent
    local file=$1 suffix=$2 m off key klen ty
    m=$(LC_ALL=C grep -aboE "[a-z0-9_]+\.$suffix" "$file" 2>/dev/null |
        sed -n '1p') || true
    [ -n "$m" ] || return 0
    off=${m%%:*}; key=${m#*:}; klen=${#key}
    ty=$(od -An -t u4 -j $((off + klen)) -N 4 "$file" 2>/dev/null | tr -d ' ')
    [ "$ty" = 4 ] || return 0
    od -An -t u4 -j $((off + klen + 4)) -N 4 "$file" 2>/dev/null | tr -d ' '
  }

  LLAMA_MOE_ARGS=()    # appended to every llama-bench command
  LLAMA_MOE_SERVER=""  # the same arguments for llama-server, one string
  LLAMA_MOE_INFO=""
  moe_experts=$(gguf_u32 "$GGUF" expert_count)
  if [ -n "$moe_experts" ] && [ "$moe_experts" -gt 0 ]; then
    moe_blocks=$(gguf_u32 "$GGUF" block_count)
    [ -n "$moe_blocks" ] || moe_blocks=$moe_experts
    bench_help=$("$LLAMA_BENCH" --help 2>&1 || true)
    server_help=$("$LLAMA_SERVER" --help 2>&1 || true)
    if printf '%s\n' "$bench_help" | grep -q -- '--n-cpu-moe' &&
       printf '%s\n' "$server_help" | grep -q -- '--n-cpu-moe'; then
      # The first count that loads and measures; probing upward in steps of 4
      # starts from the card holding everything and trades layers away only
      # as far as allocation actually requires.
      moe_layers=""
      for ((l=0; l<=moe_blocks; l+=4)); do
        probe=$(mktemp)
        if "$LLAMA_BENCH" -m "$GGUF" -p 512 -n 1 -d 0 -ngl 99 -fa on -r 1 \
             -ncmoe "$l" -o csv >"$probe" 2>&1; then
          moe_layers=$l
          rm -f "$probe"
          break
        fi
        rm -f "$probe"
      done
      if [ -n "$moe_layers" ]; then
        LLAMA_MOE_ARGS=(-ncmoe "$moe_layers")
        LLAMA_MOE_SERVER="-ncmoe $moe_layers"
        LLAMA_MOE_INFO="MoE offload: $moe_experts experts over $moe_blocks blocks; llama.cpp keeps the experts of the first $moe_layers layers on the host (--n-cpu-moe $moe_layers)"
      else
        LLAMA_MOE_INFO="MoE offload: $moe_experts experts over $moe_blocks blocks; no --n-cpu-moe count loaded, llama.cpp arms are left unoffloaded"
      fi
    elif printf '%s\n' "$bench_help" | grep -q -- '--override-tensor' &&
         printf '%s\n' "$server_help" | grep -q -- '--override-tensor'; then
      LLAMA_MOE_ARGS=(-ot '\.ffn_(up|down|gate)_exps\.=CPU')
      LLAMA_MOE_SERVER='-ot \.ffn_(up|down|gate)_exps\.=CPU'
      LLAMA_MOE_INFO="MoE offload: $moe_experts experts over $moe_blocks blocks; llama.cpp -ot '\.ffn_(up|down|gate)_exps\.=CPU' (no --n-cpu-moe in this build)"
    else
      LLAMA_MOE_INFO="MoE offload: unsupported (this llama.cpp build has neither --n-cpu-moe nor --override-tensor); llama.cpp arms are not compared"
      NO_LLAMA=1
      LLAMA_WARN=""
    fi
    [ -z "$LLAMA_MOE_INFO" ] || echo "$LLAMA_MOE_INFO"
  fi
fi

export LD_LIBRARY_PATH="$ROOT/build/core${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export SONICBOOM_GEMMA_GGUF="$GGUF"   # the loader entry point, arch-generic

if [ "$BUILD" = 1 ]; then
  for b in longctx_bench prefill_bench prefix_cache_bench; do
    bash "$BASELINE/build_${b}.sh" >/dev/null
  done
  if [ "$SPEC" = 1 ]; then
    cmake --build "$ROOT/build" --target codeedit_bench >/dev/null
  fi
fi

# The standard tiers measure the runtime's own decode and prefill rates, so
# speculation is off for every SonicBoom process they start. The --spec arms
# set off/auto on their own command lines and are not affected by this default.
export SONICBOOM_SPEC=off

# --- measurement conditions -------------------------------------------------
# Pinned clocks, and a governor that is reported but never touched. The point of
# the pin is not that a fixed clock is the "real" clock but that it is the clock
# every run in the session reports at; clocks move more than the differences
# between sessions.

CLOCK_LOCKED=""
CLOCK_SAMPLES=""        # file of the measurement window that is open
CLOCK_SAMPLER_PID=""
CLOCK_WINDOW_NAME=""
# Every window's readings, concatenated: the summary covers measurement time
# only, not the loading, warm-up and idle time around it.
CLOCK_ALL=$(mktemp "${TMPDIR:-/tmp}/boom-sm-clock-all.XXXXXX" 2>/dev/null || true)

sm_clock_mhz() { # current SM clock in MHz, empty when unreadable
  # sed reads the whole stream, unlike `head -1`: under `set -o pipefail` an
  # early-exiting head turns nvidia-smi's SIGPIPE into a 141 status and, on a
  # Blackwell card (whose clocks.max.gr query prints a cosmetic warning), that
  # used to kill the script from the EXIT trap.
  nvidia-smi --query-gpu=clocks.sm --format=csv,noheader,nounits 2>/dev/null |
    sed -n '1p' | tr -d ' '
}

# Sampling is confined to the windows in which an item is being measured. A
# sampler left running for the whole script samples the idle GPU between items
# too, and its median then describes the gaps rather than the load. The query
# is plain nvidia-smi: no root, no device state change.
measure_begin() { # NAME
  CLOCK_WINDOW_NAME=$1
  command -v nvidia-smi >/dev/null 2>&1 || return 0
  CLOCK_SAMPLES=$(mktemp "${TMPDIR:-/tmp}/boom-sm-clock.XXXXXX" 2>/dev/null) || {
    CLOCK_SAMPLES=""; return 0; }
  (
    while :; do
      nvidia-smi --query-gpu=clocks.sm,clocks.mem --format=csv,noheader,nounits \
        2>/dev/null >> "$CLOCK_SAMPLES" || true
      sleep 0.5
    done
  ) &
  CLOCK_SAMPLER_PID=$!
}

clock_stats() { # NAME FILE -> one summary line, empty when there is no reading
  awk -F, -v name="$1" '
    { gsub(/[ \t\r]/, "") }
    $1 ~ /^[0-9]+$/ {
      # The first reading of a window can land before the workload has been
      # launched; it describes the hand-off, not the measurement.
      if (!seen) { seen = 1; next }
      n++; s = $1 + 0
      if (n == 1 || s < min) min = s
      if (n == 1 || s > max) max = s
      v[n] = s
      m = $2 + 0
      if (n == 1 || m < memmin) memmin = m
      if (n == 1 || m > memmax) memmax = m
    }
    END {
      if (n == 0) exit
      for (i = 1; i <= n; i++)
        for (j = i + 1; j <= n; j++)
          if (v[i] > v[j]) { t = v[i]; v[i] = v[j]; v[j] = t }
      printf "gpu clock [%s]: SM %d-%d MHz (median %d) over %d samples, mem %d-%d MHz\n",
             name, min, max, v[int((n+1)/2)], n, memmin, memmax
    }' "$2"
}

measure_end() {
  if [ -n "$CLOCK_SAMPLER_PID" ]; then
    kill "$CLOCK_SAMPLER_PID" 2>/dev/null || true
    wait "$CLOCK_SAMPLER_PID" 2>/dev/null || true
    CLOCK_SAMPLER_PID=""
  fi
  [ -n "$CLOCK_SAMPLES" ] || return 0
  clock_stats "$CLOCK_WINDOW_NAME" "$CLOCK_SAMPLES" || true
  [ -n "$CLOCK_ALL" ] && cat "$CLOCK_SAMPLES" >> "$CLOCK_ALL" || true
  rm -f "$CLOCK_SAMPLES"
  CLOCK_SAMPLES=""
}

report_sm_clock() { # summary over every measurement window of the run
  [ -n "$CLOCK_ALL" ] || return 0
  clock_stats "all measurement windows" "$CLOCK_ALL" || true
  rm -f "$CLOCK_ALL"
  CLOCK_ALL=""
}

restore_clocks() {
  report_sm_clock
  if [ -n "$CLOCK_LOCKED" ]; then
    nvidia-smi -rgc >/dev/null 2>&1 || true
    echo "gpu clock: released (nvidia-smi -rgc)" >&2
  fi
}
cleanup() {
  restore_clocks
  [ -n "${RUN_TMP:-}" ] && rm -rf "$RUN_TMP"
  return 0
}
trap cleanup EXIT

lock_clocks() {
  if [ "$CLOCKS" != 1 ]; then
    echo "gpu clock: not pinned (--no-lock-clocks: readings are unlocked)"
    return 0
  fi
  if ! command -v nvidia-smi >/dev/null 2>&1 || ! nvidia-smi -L >/dev/null 2>&1; then
    echo "gpu clock: no NVIDIA device visible — readings are unlocked"
    return 0
  fi
  if [ -z "$CLOCK_MHZ" ]; then
    # `|| true`: the script runs under `set -e`, and a driver that cannot
    # answer clocks.max.gr (or a non-root query that fails) must not abort the
    # whole benchmark — that failure mode is exactly what this branch handles.
    CLOCK_MHZ=$(nvidia-smi --query-gpu=clocks.max.gr --format=csv,noheader,nounits \
                  2>/dev/null | sed -n '1p' | tr -d ' ' || true)
  fi
  case "$CLOCK_MHZ" in
    ''|*[!0-9]*)
      echo "gpu clock: could not read clocks.max.gr — readings are unlocked"
      return 0 ;;
  esac
  if nvidia-smi -lgc "$CLOCK_MHZ" >/dev/null 2>&1; then
    CLOCK_LOCKED=1
    echo "gpu clock: pinned to ${CLOCK_MHZ} MHz (nvidia-smi -lgc), released on exit"
  else
    echo "gpu clock: could not pin to ${CLOCK_MHZ} MHz — needs root, readings are unlocked"
    echo "           to pin it yourself: sudo nvidia-smi -lgc ${CLOCK_MHZ}"
    # Without the pin the "same clock on both sides" property is not something
    # this script enforced, so say what the clock actually is: what it reads at
    # this moment, and (at exit) the range it ran over. Both probes are
    # best-effort: `|| true` keeps `set -e` from turning an unreadable clock
    # into a failed run (the sampler below is the authoritative record).
    local now
    now=$(sm_clock_mhz || true)
    if [ -n "$now" ]; then
      echo "           SM clock now ${now} MHz (idle); each item's measurement clock is reported below"
    else
      echo "           SM clock unreadable now; each item's measurement clock is reported below"
    fi
  fi
}

report_governor() {
  local f=/sys/devices/system/cpu/cpu0/cpufreq/scaling_governor g
  if [ -r "$f" ]; then
    g=$(cat "$f")
    echo "cpu governor: $g"
    if [ "$g" != performance ]; then
      echo "           (not 'performance'; this script never changes it — if you want a"
      echo "            quieter comparison: sudo cpupower frequency-set -g performance)"
    fi
  else
    echo "cpu governor: no cpufreq interface — the CPU clock is governed by firmware"
  fi
}

lock_clocks
report_governor
echo "speculation: off (decode/prefill tiers)"

# --- helpers ---------------------------------------------------------------
res_field() { # KEY ; RESULT line on stdin -> value of KEY
  awk -v k="$1" '{for(i=1;i<=NF;i++){split($i,a,"="); if(a[1]==k){print a[2]; exit}}}'
}

median() { # numbers on stdin -> median
  sort -n | awk '{a[NR]=$1} END{
    if(NR==0){print "nan"} else if(NR%2){print a[(NR+1)/2]} else {printf "%.3f", (a[NR/2]+a[NR/2+1])/2}}'
}

# Sample standard deviation (n-1). "nan" below two samples: a spread is not
# defined there rather than zero, and a fake 0 would read as perfect
# repeatability.
stdev() { # numbers on stdin -> standard deviation or "nan"
  sort -n | awk '{a[NR]=$1; s+=$1} END{
    if(NR<2){print "nan"; exit}
    m=s/NR; t=0
    for(i=1;i<=NR;i++) t+=(a[i]-m)^2
    printf "%.4f", sqrt(t/(NR-1))}'
}

stats() { # numbers on stdin -> "<median> <stdev>"
  local vals
  vals=$(cat)
  printf '%s %s' "$(printf '%s\n' "$vals" | median)" "$(printf '%s\n' "$vals" | stdev)"
}

# "52.5 ± 0.058" — a value with its spread, the form every row reports. %g, not
# a fixed number of decimals: the metrics differ by three orders of magnitude
# (52.5 tok/s against 1692 tok/s a step), and neither a fixed decimal count nor
# an exponent suits both.
pm() { # MEDIAN SD -> "M ± SD" / "n/a"
  awk -v m="$1" -v s="$2" 'BEGIN{
    if(m=="nan"||m=="n/a"){print "n/a"; exit}
    if(s=="nan"||s=="n/a"){printf "%g", m; exit}
    printf "%g ± %g", m, s}'
}

# Every bench_stats run keeps its tool's stderr in a log under the run
# directory: a measurement tool that fails (a rejected model, a refused
# allocation) prints no RESULT line and would otherwise surface as an empty
# cell with its own explanation thrown away. bench_failures prints the tail of
# each failed metric's log under the table it belongs to.
bench_failed_file() { # the failure record lives in a file: bench_stats runs
  echo "${RUN_TMP:-${TMPDIR:-/tmp}}/bench-failed.tsv"   # in a subshell
}
bench_stats() { # KEY CMD... ; "<median> <stdev>" of RUNS runs of CMD's RESULT KEY
  local key=$1; shift
  local vals="" v log
  log=$(mktemp "${RUN_TMP:-${TMPDIR:-/tmp}}/bench-log.XXXXXX")
  for ((i=1;i<=RUNS;i++)); do
    v=$("$@" 2>>"$log" | grep '^RESULT ' | res_field "$key") || v=""
    [ -n "$v" ] && vals="$vals$v\n"
  done
  if [ -z "$vals" ]; then # no run produced the value: this cell stays empty
    printf '%s\t%s\t%s\n' "$key" "$*" "$log" >>"$(bench_failed_file)"
  fi
  printf '%b' "$vals" | stats
}

bench_failures() { # print the last words of every metric that produced no value
  local f; f=$(bench_failed_file)
  [ -s "$f" ] || return 0
  local key cmd log
  while IFS=$'\t' read -r key cmd log; do
    [ -n "$key" ] || continue
    echo "! no $key RESULT: $cmd"
    echo "  last 5 stderr lines ($log):"
    tail -n 5 "$log" | sed 's/^/    /'
  done <"$f"
  rm -f "$f"
}

ratio() { # SB LL -> "1.03x", "n/a" or "skipped"
  awk -v a="$1" -v b="$2" 'BEGIN{
    if(b=="skipped"){print "skipped"; exit}
    if(a=="nan"||b=="nan"||b+0==0){print "n/a"} else {printf "%.2fx", a/b}}'
}

fmt() { # number|nan|n/a|skipped -> one decimal (except the words)
  awk -v v="$1" 'BEGIN{ if(v=="nan"||v=="n/a"||v=="skipped") print v; else printf "%.1f", v }'
}

num1() { # number|nan|n/a|"" -> one decimal, "n/a" when there is no number
  awk -v v="$1" 'BEGIN{
    if(v==""||v=="nan"||v=="n/a"){print "n/a"; exit}
    printf "%.1f", v}'
}

row() { # LABEL BOOM_MEDIAN BOOM_SD LL RATIO UNIT
  printf '| %-14s | %18s %-5s | %10s %-5s | %6s |\n' \
    "$1" "$(pm "$2" "$3")" "$6" "$(fmt "$4")" "$6" "$5"
}

# --- warm-up table (--tune-import / --tune-export) -------------------------
# A fresh temporary cache directory is used whenever the table is moved, so an
# export holds the records this run resolved for the model under test and an
# import starts from exactly the file named. sb-tune is built from the same
# checkout (it links libsonicboom.so) and reads the cache location from the same
# environment the runtime does.
RUN_TMP=$(mktemp -d)
boom_tune() {
  local t="$ROOT/tools/sb-tune"
  [ -x "$t" ] || bash "$ROOT/tools/build_sb_tune.sh" >/dev/null
  "$t" "$@"
}
if [ -n "$TUNE_IMPORT" ] || [ -n "$TUNE_EXPORT" ]; then
  export SONICBOOM_TUNE_DIR="$RUN_TMP/tune"
  mkdir -p "$SONICBOOM_TUNE_DIR"
  # sb-tune moves the MLIR autotune file (autotune/sm_<NN>.bin) as well as the
  # decision records, and that cache is rooted at XDG_CACHE_HOME. Point it at
  # the same temporary cache: an import must start from an empty table (sb-tune
  # refuses a non-empty destination, and a pre-existing autotune file counts),
  # and the arms then read only what the archive holds.
  export XDG_CACHE_HOME="$RUN_TMP/xdg"
  mkdir -p "$XDG_CACHE_HOME"
fi
if [ -n "$TUNE_IMPORT" ]; then
  [ -f "$TUNE_IMPORT" ] || { echo "tune table not found: $TUNE_IMPORT" >&2; exit 2; }
  import_file="$TUNE_IMPORT"
  # sb-tune export yields one archive today; if a tar of archives is given, the
  # archive inside is the one to import.
  if tar -tf "$import_file" >/dev/null 2>&1; then
    mkdir -p "$RUN_TMP/untar"
    tar -xf "$import_file" -C "$RUN_TMP/untar"
    import_file=$(find "$RUN_TMP/untar" -type f | sed -n '1p')
    [ -n "$import_file" ] || { echo "tune archive is empty: $TUNE_IMPORT" >&2; exit 2; }
  fi
  boom_tune import --in "$import_file" >/dev/null
  echo "tune table: imported $TUNE_IMPORT" >&2
fi

# --- SonicBoom -------------------------------------------------------------
# Each metric reports the median of RUNS runs *and* their spread: the median
# alone cannot say whether a later comparison's difference is bigger than this
# harness's own repeatability.
measure_begin tg64
boom_tg64_stats=$(bench_stats tok_s "$BASELINE/longctx_bench" --depth 0 --steps 64)
measure_end
# d512 measures plain decode: speculation is pinned off for the row (not left to
# whatever this script exports) and the session is sized for the whole measured
# segment — depth + steps + the tool's 8 warm steps + margin — so all 64 steps
# complete. d512-spec is the same segment with SONICBOOM_SPEC unset, i.e. the
# startup probe decides, and is reported separately.
D512_NCTX=600
measure_begin d512
boom_d512_stats=$(bench_stats tok_s env SONICBOOM_SPEC=off \
                  "$BASELINE/longctx_bench" --depth 512 --steps 64 \
                  --n-ctx "$D512_NCTX")
measure_end
measure_begin d512-spec
boom_d512_spec_stats=$(bench_stats tok_s env -u SONICBOOM_SPEC \
                       "$BASELINE/longctx_bench" --depth 512 --steps 64 \
                       --n-ctx "$D512_NCTX")
measure_end
# pp is the whole-call rate (N / median t_N) on a reused session; the
# fresh-session lifecycle cost is a separate scenario and is measured by the
# tool itself, not folded in.
measure_begin pp512
boom_pp512_stats=$(bench_stats pp_whole_tok_s "$BASELINE/prefill_bench" \
                   --prompt 512 --reps 3 --session reused)
measure_end
# prefix_cache_bench needs prompt token ids that are valid for the model under
# test: real_prompt.tokens is a Gemma-vocab fixture, and feeding it to Qwen
# (vocab 151936) indexes past the embedding table (CUDA kernel failure). Token
# *values* do not affect any kernel cost here (the prompt is shape-only), so
# synthesize a deterministic in-vocab prompt — ids in [2, 1000) are below every
# supported model's vocab.
TOKFILE=$(mktemp)
seq 2 1000 | tr '\n' ' ' >"$TOKFILE"
measure_begin reuse
boom_reuse_stats=$(bench_stats reuse_ms "$BASELINE/prefix_cache_bench" \
                   --prefix 512 --new 64 --steps 4 --reps 3 \
                   --tokens-file "$TOKFILE")
measure_end
rm -f "$TOKFILE"

boom_tg64="${boom_tg64_stats%% *}"; boom_tg64_sd="${boom_tg64_stats##* }"
