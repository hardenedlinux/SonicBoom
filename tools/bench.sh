# --- extended-context tiers (--long) ---------------------------------------
# One llama-bench invocation per run with -r 1: the deep tiers are long enough
# that llama-bench's internal repeats would put a single cell at tens of
# minutes. The median over RUNS process runs is the reported value, as in the
# canonical table.
if [ "$LONG" = 1 ]; then
  lb_long_ts() { # PROMPT GEN DEPTH -> median avg_ts, or "" when skipped
    local p=$1 g=$2 d=$3
    [ "$NO_LLAMA" = 0 ] || return 0
    [ -n "${LLAMA_BENCH:-}" ] && [ -x "${LLAMA_BENCH:-}" ] || return 0
    local vals="" i f
    for ((i=1;i<=RUNS;i++)); do
      f=$(mktemp)
      "$LLAMA_BENCH" -m "$GGUF" -p "$p" -n "$g" -d "$d" -ngl 99 -fa on -r 1 -o csv \
        ${LLAMA_MOE_ARGS[@]+"${LLAMA_MOE_ARGS[@]}"} >"$f" 2>/dev/null || true
      local v
      v=$(awk -F, -v P="$p" -v G="$g" -v D="$d" '
            {gsub(/"/,"")}
            NR==1 {for(i=1;i<=NF;i++) h[$i]=i; next}
            h["avg_ts"] && $(h["n_prompt"])==P && $(h["n_gen"])==G && $(h["n_depth"])==D \
              {print $(h["avg_ts"])}
          ' "$f" | sed -n '1p')
      rm -f "$f"
      [ -n "$v" ] && vals="$vals$v\n"
    done
    printf '%b' "$vals" | median
  }

  echo
  [ -z "$LLAMA_WARN" ] || echo "$LLAMA_WARN"
  echo "==== $LABEL (long context) ===="
  echo "median ± sd of $RUNS runs; decode = $LONG_STEPS tokens at depth"
  echo "pp = whole N-token prefill from position 0, same definition as llama-bench avg_ts"
  echo
  echo "| tier          | SonicBoom          | llama.cpp      |  ratio |"
  echo "|---------------|--------------------|----------------|--------|"
  for d in $LONG_DEPTHS; do
    measure_begin "d$d"
    st=$(bench_stats tok_s "$BASELINE/longctx_bench" --prefill --depth "$d" \
           --steps "$LONG_STEPS")
    sb=${st%% *}; sbsd=${st##* }
    ll=$(lb_long_ts 0 "$LONG_STEPS" "$d")
    measure_end
    lld="${ll:-nan}"; [ "$NO_LLAMA" = 1 ] && lld="skipped"
    row "d${d}" "$sb" "$sbsd" "$lld" "$(ratio "$sb" "$lld")" "tok/s"
    echo "RESULT bench_long model=$LABEL tier=d$d tok_s=$sb llama_tok_s=$lld"
  done
  for n in $LONG_DEPTHS; do
    measure_begin "pp$n"
    st=$(bench_stats pp_whole_tok_s "$BASELINE/prefill_bench" --prompt "$n" \
           --reps 1 --session reused)
    sb=${st%% *}; sbsd=${st##* }
    ll=$(lb_long_ts "$n" 0 0)
    measure_end
    lld="${ll:-nan}"; [ "$NO_LLAMA" = 1 ] && lld="skipped"
    row "pp${n}" "$sb" "$sbsd" "$lld" "$(ratio "$sb" "$lld")" "tok/s"
    echo "RESULT bench_long model=$LABEL tier=pp$n tok_s=$sb llama_tok_s=$lld"
  done
  echo
  echo "pp_marginal_tok_s (per-token cost with the per-call constant removed) is a diagnostic in prefill_bench's RESULT line."
  bench_failures
fi

# --- code editing (--spec) -------------------------------------------------
# Ten frozen edit requests (tools/bench/codeedit), each turn its own request at
# position 0 and generating the pasted file's own token count. SonicBoom runs
# through codeedit_bench (public C ABI); llama.cpp through llama-server, with
# ngram-mod as its speculative decode. Every arm is its own process and runs
# $RUNS times, the off arm included: it is the reference the auto arm is
# compared against, and its median is a measured row like any other.
if [ "$SPEC" = 1 ]; then
  SPEC_OUT="$RUN_TMP/spec"
  mkdir -p "$SPEC_OUT"
  CB="$ROOT/build/tools/bench/codeedit_bench"
  [ -x "$CB" ] || { echo "codeedit_bench not built: $CB" >&2; exit 1; }
  DATA="$ROOT/tools/bench/codeedit"
  CTX=$("$CB" --model "$GGUF" --data "$DATA" --ctx-only | sed -n 's/^ctx=//p')
  case "$CTX" in
    ''|*[!0-9]*) echo "codeedit_bench --ctx-only gave no ctx" >&2; exit 1 ;;
  esac

  echo "code editing: SonicBoom spec off, $RUNS reps" >&2
  measure_begin "codeedit off"
  SONICBOOM_SPEC=off "$CB" --model "$GGUF" --data "$DATA" --reps "$RUNS" \
    > "$SPEC_OUT/boom_off.txt"
  measure_end
  echo "code editing: SonicBoom spec auto, $RUNS reps" >&2
  measure_begin "codeedit auto"
  SONICBOOM_SPEC=auto "$CB" --model "$GGUF" --data "$DATA" --reps "$RUNS" \
    > "$SPEC_OUT/boom_auto.txt"
  measure_end

  LLAMA_OK=0
  if [ "$NO_LLAMA" = 0 ]; then
    LLAMA_OK=1
    echo "code editing: llama.cpp no spec, $RUNS reps" >&2
    measure_begin "codeedit llama off"
    moe_server_opt=()
    [ -z "$LLAMA_MOE_SERVER" ] || moe_server_opt=(--moe-args "$LLAMA_MOE_SERVER")
    guile "$ROOT/tools/bench/llama-codeedit.scm" --server "$LLAMA_SERVER" \
      --model "$GGUF" --data "$DATA" --ctx "$CTX" \
      --gen-tokens "$SPEC_OUT/boom_off.txt" --arm off --reps "$RUNS" \
      --out "$SPEC_OUT/llama_off" "${moe_server_opt[@]}" \
      > "$SPEC_OUT/llama_off.txt"
    measure_end
    echo "code editing: llama.cpp ngram-mod, $RUNS reps" >&2
    measure_begin "codeedit llama ngram-mod"
    guile "$ROOT/tools/bench/llama-codeedit.scm" --server "$LLAMA_SERVER" \
      --model "$GGUF" --data "$DATA" --ctx "$CTX" \
      --gen-tokens "$SPEC_OUT/boom_off.txt" --arm ngram-mod --reps "$RUNS" \
      --out "$SPEC_OUT/llama_ngram" "${moe_server_opt[@]}" \
      > "$SPEC_OUT/llama_ngram.txt"
    measure_end
  fi

  boom_off_ts=$(sed -n 's/^rep=[0-9]* tok_s=//p' "$SPEC_OUT/boom_off.txt" | median)
  boom_auto_ts=$(sed -n 's/^rep=[0-9]* tok_s=//p' "$SPEC_OUT/boom_auto.txt" | median)
  ll_off_ts="nan"; ll_ngram_ts="nan"
  if [ "$LLAMA_OK" = 1 ]; then
    ll_off_ts=$(sed -n 's/^rep=[0-9]* tok_s=//p' "$SPEC_OUT/llama_off.txt" | median)
    ll_ngram_ts=$(sed -n 's/^rep=[0-9]* tok_s=//p' "$SPEC_OUT/llama_ngram.txt" | median)
  fi

  # A SonicBoom auto rep is identical to the off arm turn by turn when every
  # turn's running hash matches; the hash chains all tokens of all turns seen
  # so far in the rep.
  boom_ident=$(awk '
    FNR==NR { if (substr($1,1,5) == "turn=") off[substr($1,6)] = substr($6,6); next }
    substr($1,1,5) == "turn=" {
      t = substr($1,6); r = substr($2,5); h = substr($6,6)
      if (!(r in seen)) { seen[r] = 1; reps++ }
      n[r]++
      if (off[t] == h) same[r]++ }
    END { for (i = 0; i < reps; i++) printf "%s%d/%d", (i ? " " : ""), same[i], n[i] }
  ' "$SPEC_OUT/boom_off.txt" "$SPEC_OUT/boom_auto.txt")

  # A llama.cpp ngram-mod rep is identical to the no-spec arm when every turn's
  # generated bytes are the same.
  ll_ident=""
  if [ "$LLAMA_OK" = 1 ]; then
    for ((r=0; r<RUNS; r++)); do
      same=0; n=0
      for f in "$SPEC_OUT/llama_off"/off.rep0.*.txt; do
        t=${f##*/off.rep0.}; t=${t%.txt}
        n=$((n+1))
        if cmp -s "$f" "$SPEC_OUT/llama_ngram/ngram-mod.rep$r.$t.txt"; then
          same=$((same+1))
        fi
      done
      ll_ident="$ll_ident${ll_ident:+ }$same/$n"
    done
  fi

  # The off arm ran $RUNS times too, so count distinct turns, not lines.
  turns=$(awk '/^turn=/ { sub("turn=", "", $1); t[$1] = 1 }
               END { print length(t) }' "$SPEC_OUT/boom_off.txt")
  echo
  echo "code editing: $LABEL, $turns turns, greedy, reps=$RUNS"
  printf '%-28s%5s    %s\n' "arm" "tok/s" "identical to spec off (per rep)"
  printf '%-28s%5s    %s\n' "SonicBoom spec off" "$(num1 "$boom_off_ts")" "-"
  printf '%-28s%5s    %s\n' "SonicBoom spec auto" "$(num1 "$boom_auto_ts")" "$boom_ident"
  if [ "$LLAMA_OK" = 1 ]; then
    printf '%-28s%5s    %s\n' "llama.cpp no spec" "$(num1 "$ll_off_ts")" "-"
    printf '%-28s%5s    %s\n' "llama.cpp ngram-mod" "$(num1 "$ll_ngram_ts")" "$ll_ident"
  else
    printf '%-28s%5s    %s\n' "llama.cpp no spec" "skipped" "-"
    printf '%-28s%5s    %s\n' "llama.cpp ngram-mod" "skipped" "-"
  fi
  echo "SonicBoom auto / llama.cpp ngram-mod: $([ "$LLAMA_OK" = 1 ] && ratio "$boom_auto_ts" "$ll_ngram_ts" || echo skipped)"
  if [ "$LLAMA_OK" = 1 ]; then
    ll_off_r=$ll_off_ts; ll_ngram_r=$ll_ngram_ts
  else
    ll_off_r=skipped; ll_ngram_r=skipped
  fi
  echo "RESULT codeedit model=$LABEL boom_off=$boom_off_ts boom_auto=$boom_auto_ts llama_off=$ll_off_r llama_ngram=$ll_ngram_r"

  echo
  echo "per-turn hashes (SonicBoom):"
  awk -v reps="$RUNS" '
    FNR==NR {
      # The off arm ran reps times: keep one hash per turn and its first order.
      if (substr($1,1,5) != "turn=") next
      t = substr($1,6); off[t] = substr($6,6)
      if (!(t in have)) { have[t] = 1; order[++n] = t }
      next }
    substr($1,1,5) == "turn=" {
      auto[substr($1,6), substr($2,5)] = substr($6,6) }
    END {
      printf "%-4s %-16s", "turn", "spec off"
      for (r = 0; r < reps; r++) printf " %-16s", "auto rep " r
      printf "\n"
      for (i = 1; i <= n; i++) {
        t = order[i]
        printf "%-4s %-16s", t, off[t]
        for (r = 0; r < reps; r++) printf " %-16s", auto[t, r]
        printf "\n"
      }
    }' "$SPEC_OUT/boom_off.txt" "$SPEC_OUT/boom_auto.txt"
fi

