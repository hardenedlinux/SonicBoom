if [ "$NO_LLAMA" = 0 ]; then
  csvs=()
  measure_begin llama.cpp
  for ((i=1;i<=RUNS;i++)); do
    f=$(mktemp)
    "$LLAMA_BENCH" -m "$GGUF" -p 0,512 -n 64,0 -d 0,512 -ngl 99 -fa on -r 3 -o csv \
      ${LLAMA_MOE_ARGS[@]+"${LLAMA_MOE_ARGS[@]}"} >"$f" 2>/dev/null || true
    csvs+=("$f")
  done
  measure_end
  lb_ts() { # PROMPT GEN DEPTH -> median avg_ts across the RUNS csv files
    local p=$1 g=$2 d=$3
    for f in "${csvs[@]}"; do
      awk -F, -v P="$p" -v G="$g" -v D="$d" '
        {gsub(/"/,"")}   # llama-bench CSV quotes every field
